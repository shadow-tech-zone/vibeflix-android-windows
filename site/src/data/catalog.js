export function buildHomeRows(items, profileName) {
  return [
    {
      id: "continue-watching",
      title: `Continue Watching for ${profileName}`,
      items: items.filter((item) => item.progress > 0),
    },
    {
      id: "trending",
      title: "Trending Now",
      items: items.filter((item) => item.year === "2026" || item.match.startsWith("98") || item.match.startsWith("97")),
    },
    {
      id: "popular",
      title: "Popular on VibeFlix",
      items: items.filter((item) => ["orbit-house", "blue-hour", "river-of-glass", "northbound"].includes(item.id)),
    },
    {
      id: "series",
      title: "Binge-worthy Series",
      items: items.filter((item) => item.type === "Series"),
    },
    {
      id: "films",
      title: "Films for You",
      items: items.filter((item) => item.type === "Film"),
    },
  ].filter((row) => row.items.length > 0);
}
